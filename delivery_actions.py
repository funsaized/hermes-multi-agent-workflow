#!/usr/bin/env python3
"""Deterministic gate-send hook — proposals and deliverables, one message each.

Task bodies generated by the engine instruct workers to run this adapter for
BOTH sends that cross the human gate. It closes two "silent failure" holes:
setting an item's status notifies no one, and raw `hermes send --file` sends
file *contents as message text*, which Discord chunks into a rapid burst of
2000-char messages — long proposals reliably trip Discord's rate limit that
way. This adapter instead sends ONE message with the file as a native
attachment (`MEDIA:<path>`), retries a bounded number of times on a 429, and
otherwise fails loudly.

    python delivery_actions.py --config triage.yaml deliver       <slug> [--file <path>] [--dry-run]
    python delivery_actions.py --config triage.yaml send-proposal <slug> [--file <path>] [--dry-run] [--resend]

(The old no-subcommand form `delivery_actions.py <slug>` still means `deliver`,
for task cards created before the split.)

Deliverable resolution, in order:
  1. `--file` (absolute or workspace-relative; must live inside the item's
     persistent workspace).
  2. `paths.<path>.deliverable` from triage.yaml — a filename or glob resolved
     inside the workspace that must match exactly one file.
  3. A single `deliverable.*` / `DELIVERABLE.*` file in the workspace root.
Anything ambiguous or missing is a hard, listed failure — the worker blocks its
task with the JSON error instead of improvising.

Proposal resolution: `--file`, else `<workspace_root>/proposals/<slug>.md` —
the exact path the propose task body tells its worker to render to.

Both sends use the supported Hermes messaging surface (`hermes send`) with a
short deterministic caption plus the file attached, so one adapter call is one
platform message regardless of file length. On a 429 the adapter sleeps
(15s → 45s → 120s) and retries; after that it exits non-zero and the worker
blocks with the JSON error — workers never hand-roll retry loops (an
improvised retry burst is what escalates a per-channel limit into a tripped
global bucket).

`--dry-run` resolves and validates everything, prints the exact command, and
mutates nothing — the synthetic eval uses it.

Environment: TRIAGE_CONFIG, TRIAGE_VAULT_DIR, HERMES_KANBAN_DB, HERMES_HOME,
HERMES_KANBAN_TASK (used only to comment on the running task).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

from engine.config import TriageConfig
from engine.engine import TriageEngine
from engine.item_vault import ItemVault, utc_now_iso
from engine.kanban_store import KanbanStore
from proposal_actions import (
    append_note,
    board_db,
    die_backend,
    die_input,
    die_state,
    first_linked_task,
    item_slug,
    vault_dir,
)

DELIVERABLE_FALLBACK_GLOBS = ("deliverable.*", "DELIVERABLE.*")

# Discord's hard message cap is 2000 chars; a caption under this limit rides on
# the attachment message itself (hermes `_media_caption_split`), so the whole
# send stays a single platform message. Other platforms are no stricter here.
GATE_CAPTION_LIMIT = 1800

# Bounded backoff between attempts when the platform answers 429. Three sleeps
# → four attempts total, then a hard failure the worker blocks with.
RATE_LIMIT_RETRY_DELAYS = (15, 45, 120)
_RATE_LIMIT_RE = re.compile(r"\b429\b|rate.?limit", re.IGNORECASE)

# Statuses whose gate decision is already made — never (re)send a proposal.
PROPOSAL_FORBIDDEN_STATUSES = {
    "approved", "delivered", "shelved_by_human", "shelved_below_threshold",
}


def load_config(config_path: str | Path | None = None) -> TriageConfig:
    return TriageConfig.load(config_path or os.environ.get("TRIAGE_CONFIG") or "triage.yaml")


def resolve_deliverable(workspace: Path, pattern: str | None, explicit: str | None) -> Path:
    """Deterministically pick the file to send, or raise with the evidence."""
    if explicit:
        candidate = Path(explicit)
        if not candidate.is_absolute():
            candidate = workspace / candidate
        candidate = candidate.resolve()
        if not candidate.is_file():
            raise FileNotFoundError(f"--file {explicit!r} does not exist under {workspace}.")
        if workspace != candidate and workspace not in candidate.parents:
            raise ValueError(f"--file {explicit!r} resolves outside the item workspace {workspace}.")
        return candidate

    if not workspace.is_dir():
        raise FileNotFoundError(
            f"Item workspace {workspace} does not exist; fulfillment stages must write there."
        )

    patterns = [pattern] if pattern else list(DELIVERABLE_FALLBACK_GLOBS)
    matches: list[Path] = []
    for glob_pattern in patterns:
        matches.extend(p for p in sorted(workspace.glob(glob_pattern)) if p.is_file())
    if len(matches) == 1:
        return matches[0].resolve()

    listing = sorted(p.name for p in workspace.iterdir())[:20]
    if not matches:
        raise FileNotFoundError(
            f"No deliverable matched {patterns} in {workspace}. Set `paths.<path>.deliverable` "
            f"in triage.yaml or pass --file. Workspace contains: {listing}."
        )
    raise ValueError(
        f"Deliverable pattern {patterns} is ambiguous in {workspace}: "
        f"{[m.name for m in matches]}. Set a more specific `paths.<path>.deliverable` or pass --file."
    )


def resolve_proposal_file(config: TriageConfig, slug: str, explicit: str | None) -> Path:
    """The rendered proposal to attach — explicit --file, else the canonical path."""
    if explicit:
        candidate = Path(explicit)
        if not candidate.is_absolute():
            candidate = Path(config.hermes.project_root) / candidate
        candidate = candidate.resolve()
        if not candidate.is_file():
            raise FileNotFoundError(f"--file {explicit!r} does not exist.")
        return candidate
    candidate = (config.workspace_path / "proposals" / f"{slug}.md").resolve()
    if not candidate.is_file():
        raise FileNotFoundError(
            f"No rendered proposal at {candidate}. Render the proposal there first "
            "(the propose task body names this exact path), then re-run send-proposal."
        )
    return candidate


